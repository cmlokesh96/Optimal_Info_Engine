@njit(cache=True)
def current_matrix_numba(t, params):
    """Evaluates matrix exponential computed using Wolfram Mathematica at given time.

        Parameters: 
        t: float, time of evaluation
        params: SystemVariables

    returns 4x4 matrix saved in numpy ndarray"""
    tau_b = params.tau_b
    tau_p = params.tau_p

    tau_sum = tau_b + tau_p
    trig_argument = np.sqrt(1 + tau_b / tau_p) / tau_b
    sqrt_tau_p = np.sqrt(tau_p)
    tau_sum_sqrt = np.sqrt(tau_sum)
    tau_sum_three_half = tau_sum_sqrt ** 3
    tau_p_three_half = sqrt_tau_p ** 3
    tau_b_squared = tau_b ** 2
    sqrt_sum_times_tau_p = sqrt_tau_p * tau_sum_sqrt

    matrix = np.empty((4, 4))
    sinh_val = np.sinh(t*trig_argument)
    cosh_val = np.cosh(t*trig_argument)

    matrix[0,0] = (tau_b + t + tau_b*cosh_val + 2* tau_p)/(2*tau_sum)- sinh_val * tau_b * sqrt_tau_p/(2*tau_sum_three_half)
    matrix[0,1] = sqrt_tau_p* tau_b_squared*sinh_val/tau_sum_three_half + tau_p*t/tau_sum
    matrix[0,2] = -(-tau_b + t + tau_b*cosh_val)/(2*tau_sum)+ sinh_val * tau_b * sqrt_tau_p/(2*tau_sum_three_half)
    matrix[0,3] =  tau_b*((t + tau_b - cosh_val*tau_b)/(2*tau_sum) -tau_b*sqrt_tau_p * sinh_val/(2*tau_sum_three_half))

    matrix[1,0] = (1-cosh_val)/(2*tau_sum) + sinh_val/(2*sqrt_sum_times_tau_p)
    matrix[1,1] = (cosh_val*tau_b +tau_p)/tau_sum
    matrix[1,2] = - matrix[1,0]
    matrix[1,3] = -tau_b*0.5*(sinh_val/sqrt_sum_times_tau_p + (cosh_val-1)/tau_sum)

    matrix[2,0] = (0.5*t + tau_p - tau_p* cosh_val)/(tau_sum) + sinh_val*(0.5*tau_b*sqrt_tau_p+ tau_p_three_half)/(tau_sum_three_half)
    matrix[2,1] = tau_p*((t +tau_b* cosh_val - tau_b)/(tau_sum)-tau_b * sqrt_tau_p*sinh_val/tau_sum_three_half)
    matrix[2,2] = -(0.5*t - tau_b - tau_p*cosh_val)/(tau_sum) - sinh_val*(0.5*tau_b*sqrt_tau_p+ tau_p_three_half)/(tau_sum_three_half)
    matrix[2,3] = -sqrt_tau_p* tau_b_squared*sinh_val/(2*tau_sum_three_half) + tau_b*t/(2*tau_sum)

    matrix[3,0] = - np.sinh(0.5*t*trig_argument)**2/tau_sum
    matrix[3,1] = sqrt_tau_p*(- sinh_val/tau_sum_sqrt +(1 -cosh_val)*sqrt_tau_p/tau_sum)
    matrix[3,2] = - matrix[3,0]
    matrix[3,3] = (sinh_val* sqrt_sum_times_tau_p + tau_b*0.5 +cosh_val*(0.5*tau_b+ tau_p))/tau_sum

    return matrix

class SolutionMatrixCreator:
    """
    wrapper storing params for reuse, plus the two/three scalar
    attributes (tau_p, k) other code reuses, delegates entirely to
    current_matrix_numba
    """
    def __init__(self, params):
        self.params = params
        self.tau_b = params.tau_b
        self.tau_p = params.tau_p
        self.k = params.k

    def current_matrix(self, t):
        return current_matrix_numba(t, self.params)

@njit(cache=True)
def current_lambda(current_B, c_vector, params):
    """
    Function to compute the optimal trap focus lambda at time t. 
    Parameters:
    current_B: ndarray as generated by SolutionMatrixCreator.current_matrix
    c_vector: np.array with 4 entries, without lambda_f, as returned by get_cvector
    params: SystemVariables object

    Returns: float, lambda(t)"""
    current_solution = current_B @ c_vector
    optim_lambda = (params.tau_p *current_solution[1] + (params.k+1)* current_solution[0] - current_solution[2])/params.k

    return optim_lambda

def make_optimal_protocol_numba(c_vector, t_protocol_end, lambda_f):
    """
    Build a numba-jitted protocol callable matching the signature expected by
    euler_maruyama_ensemble_bath_model's protocol argument
    parameters is supplied at call by the integrator (the same
    SystemVariables passed to euler_maruyama_ensemble_bath_model), so only
    the protocol-specific values are needed

    Parameters: 
    current_B: ndarray as generated by SolutionMatrixCreator.current_matrix
    c_vector: np.array with 4 entries, without lambda_f, as returned by get_cvector
    t_end_protocol: float

    Return: numba compatible optimal protocol function for integrator
    """
    c_vector = np.asarray(c_vector, dtype=np.float64)

    @njit(cache=True)
    def optimal_protocol(t, parameters):
        if t >= t_protocol_end:
            return lambda_f
        B = current_matrix_numba(t, parameters)
        return current_lambda(B, c_vector, parameters)

    return optimal_protocol

def _expand(row):
    """Pad a  row with a trailing 0 """
    return np.concatenate([row, [0.0]])


def _integrand_matrix(t, B_creator):
    """The matrix D has integral contributions. the integrands of those are build as a 5x5 integrand matrix at once
    parameters:
    t: time of evaluation in the integration process
    B_creator: SolutionMatrixCreator

    Returns: 5x5 ndarray containing integrands for D"""
    B = B_creator.current_matrix(t)
    row2 = _expand(B[1, :])
    row3 = _expand(B[2, :])

    # tau_p * row2 outer row2  -  0.5*(row3 outer row2 + row2 outer row3)
    return (B_creator.tau_p * np.outer(row2, row2) - 0.5 * (np.outer(row3, row2) + np.outer(row2, row3)))


def compute_D(B_creator,t_protocol_end, params):
    """Compute matrix defined such that W=c^TDc (c including lambda_f)

    Parameters:
    t_protocol_end: float
    B_creator: SolutionMatrixCreator
    params: SystemVariables

    Returns: 5x5 ndarray"""

    final_B = B_creator.current_matrix(t_protocol_end)
    final_row0 = _expand(final_B[0, :])          # length-5, last entry padded with 0

    e0 = np.zeros(5); e0[0] = 1.0
    e4 = np.zeros(5); e4[4] = 1.0

    # Vectorized version of the two algebraic (non-integral) terms
    term_k   = params.k / 2 * (np.outer(e4, e4) - np.outer(e4, final_row0) - np.outer(final_row0, e4))
    term_kplus1 = (params.k + 1) / 2 * (np.outer(final_row0, final_row0) - np.outer(e0, e0))

    # Single vectorized integration call
    integral, _ = quad_vec(lambda t: _integrand_matrix(t, B_creator), 0,t_protocol_end)

    D = (term_k + term_kplus1 + integral) * params.kappa / params.k
    return D
 
def compute_c2(c1,c3, D):
    """compute c2 = v* using the explicitly solved optimization using the D Matrix paraphrasing the work.

    parameters:
    c1: mean initial paricle position
    c_3: mean initial bath particle position
    D: ndarray containing the explicit matrix s.t. W= c^T D c

    return:
    scalar optimal initial velocity"""
    res = -((c1 * (D[0,4] * D[1,4] * D[3,3] - D[0,4] * D[1,3] * D[3,4] - D[0,3] * D[1,4] * D[3,4] + D[0,1] * D[3,4]**2 + 
        D[0,3] * D[1,3] * D[4,4] - D[0,1] * D[3,3] * D[4,4]) + 
        c3 * (D[1,4] * D[2,4] * D[3,3] - D[1,4] * D[2,3] * D[3,4] - D[1,3] * D[2,4] * D[3,4] + D[1,2] * D[3,4]**2 + 
        D[1,3] * D[2,3] * D[4,4] - D[1,2] * D[3,3] * D[4,4]))/
        (D[1,4]**2 * D[3,3] - 2 * D[1,3] * D[1,4] * D[3,4] + D[1,3]**2 * D[4,4] + D[1,1] * (D[3,4]**2 - D[3,3] * D[4,4])))
    return res

def compute_c4(c1,c3, D):
    """compute c4 = Lambda* using the explicitly solved optimization using the D Matrix paraphrasing the work.

    parameters:
    c1: mean initial paricle position
    c_3: mean initial bath particle position
    D: ndarray containing the explicit matrix s.t. W= c^T D c

    return:
    scalar optimal Lagrange multiplier"""
    res = (c1 * (D[0,4] * D[1,3] * D[1,4] - D[0,3] * D[1,4]**2 - D[0,4] * D[1,1] * D[3,4] + D[0,1] * D[1,4] * D[3,4] + 
        D[0,3] * D[1,1] * D[4,4] - D[0,1] * D[1,3] * D[4,4]) + 
        c3 * (-D[1,4]**2 * D[2,3] + D[1,3] * D[1,4] * D[2,4] + D[1,2] * D[1,4] * D[3,4] - D[1,1] * D[2,4] * D[3,4] - 
        D[1,2] * D[1,3] * D[4,4] + D[1,1] * D[2,3] * D[4,4]))/(
        D[1,4]**2 * D[3,3] - 2 * D[1,3] * D[1,4] * D[3,4] + D[1,3]**2 * D[4,4] + D[1,1] * (D[3,4]**2 - D[3,3] * D[4,4]))
    return res

def compute_c5(c1,c3,D):
    """compute c5 = lambda_f* using the explicitly solved optimization using the D Matrix paraphrasing the work.

    parameters:
    c1: mean initial paricle position
    c_3: mean initial bath particle position
    D: ndarray containing the explicit matrix s.t. W= c^T D c

    return:
    scalar optimal final trap position c5"""
    res = (c1 * (-D[0,4] * D[1,3]**2 + D[0,3] * D[1,3] * D[1,4] + D[0,4] * D[1,1] * D[3,3] - D[0,1] * D[1,4] * D[3,3] - 
        D[0,3] * D[1,1] * D[3,4] + D[0,1] * D[1,3] * D[3,4]) + 
        c3 * (D[1,3] * D[1,4] * D[2,3] - D[1,3]**2 * D[2,4] - D[1,2] * D[1,4] * D[3,3] + D[1,1] * D[2,4] * D[3,3] + 
        D[1,2] * D[1,3] * D[3,4] - D[1,1] * D[2,3] * D[3,4]))/(
        D[1,4]**2 * D[3,3] - 2 * D[1,3] * D[1,4] * D[3,4] + D[1,3]**2 * D[4,4] + D[1,1] * (D[3,4]**2 - D[3,3] * D[4,4]))
    return res

#Marginalized colloids positional equilibrium distribution
def eq_dist(x, params):
    sigma_squared = params.k_B * params.T/params.kappa
    return 1/np.sqrt(2*np.pi * sigma_squared) * np.exp(-x**2/(2*sigma_squared))

